using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using System;

namespace Content.Client._Horizon.UISamples.UI;

[GenerateTypedNameReferences]
public sealed partial class CrewNotesWindow : FancyWindow
{
    // События интерфейса — логику подключим позже (например, в BoundUserInterface).
    public event Action? SaveNotesButtonPressed;
    public event Action? AutoSaveCheckToggled;
    public event Action? FontSizeSliderValueChanged;
    public event Action? ThemeOptionItemSelected;

    public CrewNotesWindow()
    {
        RobustXamlLoader.Load(this);

        SaveNotesButton.OnPressed += _ => SaveNotesButtonPressed?.Invoke();
        AutoSaveCheck.OnToggled += _ => AutoSaveCheckToggled?.Invoke();
        FontSizeSlider.OnValueChanged += _ => FontSizeSliderValueChanged?.Invoke();
        ThemeOption.OnItemSelected += _ => ThemeOptionItemSelected?.Invoke();
    }

