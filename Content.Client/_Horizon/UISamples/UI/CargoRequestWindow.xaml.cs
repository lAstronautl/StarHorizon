using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using System;

namespace Content.Client._Horizon.UISamples.UI;

[GenerateTypedNameReferences]
public sealed partial class CargoRequestWindow : FancyWindow
{
    // События интерфейса — логику подключим позже (например, в BoundUserInterface).
    public event Action? SearchBarTextEntered;
    public event Action? ProductListItemSelected;
    public event Action? AmountSpinValueChanged;
    public event Action? ReasonEditTextEntered;
    public event Action? OrderButtonPressed;

    public CargoRequestWindow()
    {
        RobustXamlLoader.Load(this);

        SearchBar.OnTextEntered += _ => SearchBarTextEntered?.Invoke();
        ProductList.OnItemSelected += _ => ProductListItemSelected?.Invoke();
        AmountSpin.ValueChanged += _ => AmountSpinValueChanged?.Invoke();
        ReasonEdit.OnTextEntered += _ => ReasonEditTextEntered?.Invoke();
        OrderButton.OnPressed += _ => OrderButtonPressed?.Invoke();
    }

    // Именованные элементы (доступны как поля благодаря GenerateTypedNameReferences):
    //   LineEdit SearchBar
    //   ItemList ProductList
    //   Label ProductName
    //   RichTextLabel ProductDescription
    //   SpinBox AmountSpin
    //   LineEdit ReasonEdit
    //   Label BalanceLabel
    //   Button OrderButton
}
