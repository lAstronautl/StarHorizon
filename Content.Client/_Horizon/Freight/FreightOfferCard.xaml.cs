using Content.Client.Message;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Horizon.Freight;

[GenerateTypedNameReferences]
public sealed partial class FreightOfferCard : PanelContainer
{
    public event Action? TakePressed;

    public FreightOfferCard(string name, string description, string total, string routeMarkup)
    {
        RobustXamlLoader.Load(this);

        NameLabel.Text = name;
        DescriptionLabel.Text = description;
        DescriptionLabel.Visible = description != string.Empty;
        TotalLabel.Text = total;
        RouteLabel.SetMarkup(routeMarkup);

        TakeButton.OnPressed += _ => TakePressed?.Invoke();
    }
}
