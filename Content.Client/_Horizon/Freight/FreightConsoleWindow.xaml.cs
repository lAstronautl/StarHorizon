using Content.Client.Salvage.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._Horizon.Freight;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._Horizon.Freight;

[GenerateTypedNameReferences]
public sealed partial class FreightConsoleWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;
    [Dependency] private readonly IGameTiming _timing = default!;

    public Action<int>? OnTakeOfferPressed;
    public Action? OnSpawnPressed;
    public Action? OnSellPressed;

    private TimeSpan _nextRefresh;

    public FreightConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SpawnButton.OnPressed += _ => OnSpawnPressed?.Invoke();
        SellButton.OnPressed += _ => OnSellPressed?.Invoke();
    }

    private string DestinationName(ProtoId<FreightDestinationPrototype>? id)
    {
        return id is { } d && _proto.TryIndex(d, out var proto)
            ? Loc.GetString(proto.Name)
            : Loc.GetString("freight-no-destination");
    }

    private string EntryLine(FreightResolvedEntry e)
    {
        var name = _proto.TryIndex(e.Crate, out var crate) ? crate.Name : e.Crate.Id;
        return Loc.GetString("freight-console-entry",
            ("name", name), ("count", e.Count), ("destination", DestinationName(e.Destination)),
            ("credits", e.Credits), ("tokens", e.Tokens));
    }

    public void UpdateState(FreightConsoleBuiState state)
    {
        _nextRefresh = state.NextRefresh;
        HereLabel.Text = Loc.GetString("freight-console-here", ("destination", DestinationName(state.Here)));

        // Offers
        OffersContainer.RemoveAllChildren();
        NoOffersLabel.Visible = state.Offers.Count == 0;
        for (var i = 0; i < state.Offers.Count; i++)
        {
            var index = i;
            var offer = state.Offers[i];
            var card = new OfferingWindowOption { Title = offer.Name };

            if (offer.Description != string.Empty)
                card.AddContent(new Label { Text = offer.Description, StyleClasses = { "LabelSubText" } });

            card.AddContent(new Label
            {
                Text = Loc.GetString("freight-console-offer-source", ("source", DestinationName(offer.Source))),
            });

            foreach (var entry in offer.Entries)
            {
                card.AddContent(new Label { Text = EntryLine(entry), ClipText = false });
            }

            card.Disabled = false;
            card.ClaimPressed += _ => OnTakeOfferPressed?.Invoke(index);
            OffersContainer.AddChild(card);
        }

        // Manifest in the slot
        ManifestEntriesContainer.RemoveAllChildren();
        if (!state.HasManifest)
        {
            ManifestSourceLabel.Text = Loc.GetString("freight-console-no-manifest");
            SpawnButton.Disabled = true;
        }
        else
        {
            ManifestSourceLabel.Text = Loc.GetString("freight-console-manifest-source",
                ("source", DestinationName(state.ManifestSource)));
            foreach (var entry in state.ManifestEntries)
            {
                ManifestEntriesContainer.AddChild(new Label { Text = EntryLine(entry), ClipText = false });
            }

            // The manifest is only accepted at its own loading point.
            SpawnButton.Disabled = state.ManifestSource != null && state.ManifestSource != state.Here;
        }

        SellStatusLabel.Text = Loc.GetString("freight-console-sell-status",
            ("sellable", state.SellableCrates), ("wrong", state.WrongDestinationCrates), ("value", state.SellValue));
        SellButton.Disabled = state.SellableCrates == 0;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var remaining = _nextRefresh - _timing.CurTime;
        if (remaining < TimeSpan.Zero)
            remaining = TimeSpan.Zero;

        RefreshLabel.Text = Loc.GetString("freight-console-refresh-in",
            ("time", $"{(int) remaining.TotalMinutes:00}:{remaining.Seconds:00}"));
    }
}
