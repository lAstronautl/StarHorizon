using System.Globalization;
using System.Linq;
using System.Text;
using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._Horizon.Freight;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Horizon.Freight;

[GenerateTypedNameReferences]
public sealed partial class FreightConsoleWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;
    [Dependency] private readonly IGameTiming _timing = default!;

    private const string KeyColor = "#a0a0a0";
    private const string GoodColor = "#5fd35f";
    private const string BadColor = "#ff6b6b";
    private const string WarnColor = "#ffcc4d";

    private const int OrdersTabIndex = 0;
    private const int ManifestTabIndex = 1;

    public Action<int>? OnTakeOfferPressed;
    public Action? OnSpawnPressed;
    public Action? OnSellPressed;

    private TimeSpan _nextRefresh;
    private bool _hadManifest;

    private static readonly NumberFormatInfo Numbers = new() { NumberGroupSeparator = " ", NumberDecimalDigits = 0 };

    public FreightConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Tabs.SetTabTitle(OrdersTabIndex, Loc.GetString("freight-console-tab-orders"));
        Tabs.SetTabTitle(ManifestTabIndex, Loc.GetString("freight-console-tab-manifest"));

        SpawnButton.OnPressed += _ => OnSpawnPressed?.Invoke();
        SellButton.OnPressed += _ => OnSellPressed?.Invoke();
    }

    #region Formatting

    private static string Num(int value) => value.ToString("N0", Numbers);

    private string DestinationName(ProtoId<FreightDestinationPrototype>? id)
    {
        var name = id is { } d && _proto.TryIndex(d, out var proto)
            ? Loc.GetString(proto.Name)
            : Loc.GetString("freight-no-destination");
        return FormattedMessage.EscapeText(name);
    }

    private string CrateName(EntProtoId crate)
    {
        return FormattedMessage.EscapeText(_proto.TryIndex(crate, out var proto) ? proto.Name : crate.Id);
    }

    private string Total(List<FreightResolvedEntry> entries)
    {
        var credits = entries.Sum(e => e.Credits * e.Count);
        var tokens = entries.Sum(e => e.Tokens * e.Count);
        return Loc.GetString("freight-console-total", ("credits", Num(credits)), ("tokens", tokens));
    }

    /// <summary>
    /// "Откуда: X / Куда: • address — crates — reward", one line per delivery address.
    /// </summary>
    private string BuildRoute(ProtoId<FreightDestinationPrototype>? source, List<FreightResolvedEntry> entries,
        string? sourceSuffix = null)
    {
        var sb = new StringBuilder();
        sb.Append($"[color={KeyColor}]{Loc.GetString("freight-console-from")}[/color] [bold]{DestinationName(source)}[/bold]");
        if (sourceSuffix != null)
            sb.Append(' ').Append(sourceSuffix);

        sb.Append('\n').Append($"[color={KeyColor}]{Loc.GetString("freight-console-to")}[/color]");

        foreach (var group in entries.GroupBy(e => e.Destination))
        {
            var crates = string.Join(", ", group.Select(e => $"{CrateName(e.Crate)} ×{e.Count}"));
            var credits = group.Sum(e => e.Credits * e.Count);
            var tokens = group.Sum(e => e.Tokens * e.Count);

            sb.Append('\n').Append(Loc.GetString("freight-console-route-line",
                ("destination", DestinationName(group.Key)),
                ("crates", crates),
                ("credits", Num(credits)),
                ("tokens", tokens)));
        }

        return sb.ToString();
    }

    #endregion

    public void UpdateState(FreightConsoleBuiState state)
    {
        _nextRefresh = state.NextRefresh;
        HereLabel.SetMarkup($"[color={KeyColor}]{Loc.GetString("freight-console-here")}[/color] [bold]{DestinationName(state.Here)}[/bold]");

        UpdateOffers(state);
        UpdateManifest(state);
        UpdateSell(state);

        // Jump to the manifest tab when a manifest gets inserted.
        if (state.HasManifest && !_hadManifest)
            Tabs.CurrentTab = ManifestTabIndex;
        _hadManifest = state.HasManifest;
    }

    private void UpdateOffers(FreightConsoleBuiState state)
    {
        OffersContainer.RemoveAllChildren();
        NoOffersLabel.Visible = state.Offers.Count == 0;

        for (var i = 0; i < state.Offers.Count; i++)
        {
            var index = i;
            var offer = state.Offers[i];
            var card = new FreightOfferCard(offer.Name, offer.Description, Total(offer.Entries),
                BuildRoute(offer.Source, offer.Entries));
            card.TakePressed += () => OnTakeOfferPressed?.Invoke(index);
            OffersContainer.AddChild(card);
        }
    }

    private void UpdateManifest(FreightConsoleBuiState state)
    {
        if (!state.HasManifest)
        {
            ManifestLabel.SetMarkup($"[color={KeyColor}]{Loc.GetString("freight-console-insert-hint")}[/color]");
            SpawnButton.Disabled = true;
            return;
        }

        var atSource = state.ManifestSource == null || state.ManifestSource == state.Here;
        var status = atSource
            ? $"[color={GoodColor}]{Loc.GetString("freight-console-here-ok")}[/color]"
            : $"[color={BadColor}]{Loc.GetString("freight-console-here-wrong")}[/color]";

        ManifestLabel.SetMarkup(BuildRoute(state.ManifestSource, state.ManifestEntries, status)
                                + "\n" + Loc.GetString("freight-console-total-line", ("total", Total(state.ManifestEntries))));
        SpawnButton.Disabled = !atSource;
    }

    private void UpdateSell(FreightConsoleBuiState state)
    {
        var wrongColor = state.WrongDestinationCrates > 0 ? WarnColor : KeyColor;
        SellStatusLabel.SetMarkup(Loc.GetString("freight-console-pallets-status",
            ("sellable", state.SellableCrates),
            ("value", Num(state.SellValue)),
            ("wrong", state.WrongDestinationCrates),
            ("wrongColor", wrongColor)));
        SellButton.Disabled = state.SellableCrates == 0;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var remaining = _nextRefresh - _timing.CurTime;
        if (remaining < TimeSpan.Zero)
            remaining = TimeSpan.Zero;

        RefreshLabel.Text = Loc.GetString("freight-console-refresh-in",
            ("time", $"{(int) remaining.TotalMinutes:00}:{remaining.Seconds:00}"));
    }
}
