using Content.Client.UserInterface.Controls;
using Content.Shared._Horizon.Freight;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Horizon.Freight;

[GenerateTypedNameReferences]
public sealed partial class FreightConsoleWindow : FancyWindow
{
    public Action? OnSpawnPressed;
    public Action? OnSellPressed;
    public Action? OnRefreshPressed;

    public FreightConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        SpawnButton.OnPressed += _ => OnSpawnPressed?.Invoke();
        SellButton.OnPressed += _ => OnSellPressed?.Invoke();
        RefreshButton.OnPressed += _ => OnRefreshPressed?.Invoke();
    }

    public void UpdateState(FreightConsoleBuiState state)
    {
        DestinationLabel.Text = Loc.GetString("freight-console-destination", ("destination", state.Destination));
        AddresseeLabel.Text = state.HasManifest
            ? Loc.GetString("freight-console-addressee", ("addressee", state.Addressee))
            : Loc.GetString("freight-console-no-manifest");

        EntriesContainer.RemoveAllChildren();
        foreach (var entry in state.Entries)
        {
            EntriesContainer.AddChild(new Label
            {
                Text = Loc.GetString("freight-console-entry",
                    ("name", entry.CrateName), ("count", entry.Count),
                    ("price", entry.Price), ("destinations", entry.Destinations)),
                ClipText = false
            });
        }

        SpawnButton.Disabled = !state.HasManifest;
        SellStatusLabel.Text = Loc.GetString("freight-console-sell-status",
            ("sellable", state.SellableCrates), ("wrong", state.WrongDestinationCrates), ("value", state.SellValue));
        SellButton.Disabled = state.SellableCrates == 0;
    }
}
