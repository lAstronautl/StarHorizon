using Content.Client.UserInterface.Controls;
using Content.Shared._Horizon.Shipbreaking.Derelict;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Horizon.Shipbreaking.Derelict;

[GenerateTypedNameReferences]
public sealed partial class DerelictYardMenu : FancyWindow
{
    public event Action<string>? OnSelected;
    public event Action<string>? OnBuy;

    private DerelictYardState? _state;
    private string? _selected;

    public DerelictYardMenu()
    {
        RobustXamlLoader.Load(this);

        BuyButton.OnPressed += _ =>
        {
            if (_selected != null)
                OnBuy?.Invoke(_selected);
        };
    }

    public void UpdateState(DerelictYardState state)
    {
        _state = state;
        BalanceLabel.Text = state.Balance is { } balance ? Loc.GetString("derelict-yard-money", ("amount", balance)) : "-";

        VesselList.RemoveAllChildren();
        foreach (var vessel in state.Vessels)
        {
            var id = vessel.Id;
            var button = new Button
            {
                Text = Loc.GetString("derelict-yard-row", ("name", vessel.Name), ("price", vessel.Price)),
                HorizontalExpand = true,
                ToggleMode = true,
                Pressed = id == _selected,
            };
            button.OnPressed += _ => Select(id);
            VesselList.AddChild(button);
        }

        if (_selected == null && state.Vessels.Count > 0)
            Select(state.Vessels[0].Id);
        else
            RefreshSelected();
    }

    private void Select(string id)
    {
        _selected = id;
        Preview.Clear();
        OnSelected?.Invoke(id);
        UpdateState(_state ?? new DerelictYardState());
    }

    private void RefreshSelected()
    {
        var vessel = _state?.Vessels.Find(v => v.Id == _selected);
        if (vessel == null)
        {
            NameLabel.Text = string.Empty;
            DescriptionLabel.SetMessage(string.Empty);
            PriceLabel.Text = string.Empty;
            BuyButton.Disabled = true;
            return;
        }

        NameLabel.Text = vessel.Name;
        DescriptionLabel.SetMessage(FormattedMessage.FromUnformatted(vessel.Description));
        PriceLabel.Text = Loc.GetString("derelict-yard-price", ("price", vessel.Price), ("minutes", (int) vessel.Lifetime.TotalMinutes));
        BuyButton.Disabled = _state?.Balance is not { } balance || balance < vessel.Price;
    }

    public void SetPreview(DerelictPreviewMessage message)
    {
        if (message.Id == _selected)
            Preview.SetPreview(message.Tiles, message.Kinds);
    }
}
