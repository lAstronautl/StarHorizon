using System.Linq;
using Content.Client.Message;
using Content.Shared._Horizon.StationDeployment.Prototypes;
using Content.Shared.Research.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Horizon.StationDeployment;

[GenerateTypedNameReferences]
public sealed partial class StationOrderCardControl : BoxContainer
{
    public Action? OnCancelPressed;

    public StationOrderCardControl(StationOrderPrototype order, int currentLevel, IPrototypeManager prototypeManager, SpriteSystem spriteSys)
    {
        RobustXamlLoader.Load(this);

        CancelButton.ToolTip = Loc.GetString("station-task-console-cancel-tooltip");
        CancelButton.OnPressed += _ => OnCancelPressed?.Invoke();

        // The discipline prototype might not be available client-side - degrade gracefully instead of crashing the card.
        prototypeManager.TryIndex<TechDisciplinePrototype>(order.Category, out var discipline);

        if (order.Sprite != null)
            CategoryTexture.Texture = spriteSys.Frame0(order.Sprite);
        else if (discipline != null)
            CategoryTexture.Texture = spriteSys.Frame0(discipline.Icon);

        var categoryName = discipline != null ? Loc.GetString(discipline.Name) : order.Category.Id;
        CategoryLabel.SetMarkup(Loc.GetString("station-task-console-category-label", ("category", categoryName), ("level", currentLevel)));

        var items = order.Entries.Select(e => Loc.GetString("station-task-console-item-line", ("amount", e.Amount), ("item", Loc.GetString(e.Name))));
        ManifestLabel.SetMarkup(Loc.GetString("station-task-console-manifest-label", ("items", string.Join(", ", items))));

        if (order.Description != string.Empty)
            DescriptionLabel.SetMarkup(Loc.GetString("station-task-console-description-label", ("description", Loc.GetString(order.Description))));
    }
}
