using Content.Client.Guidebook;
using Content.Client.UserInterface.Controls;
using Content.Shared._NF.Shipyard.Prototypes;
using Content.Shared.Guidebook;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Horizon.Shipyard;

/// <summary>
/// Shows a pre-rendered image of a shipyard vessel (see Tools/_Horizon/render_shipyard_previews.py),
/// falling back to a server-built tile layout, with a link to its guidebook page.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ShipyardPreviewWindow : FancyWindow
{
    private static readonly ResPath RenderDirectory = new("/Textures/_Horizon/Shipyard/Previews");

    [Dependency] private readonly IEntitySystemManager _entitySystem = default!;
    [Dependency] private readonly IResourceCache _resourceCache = default!;

    public VesselPrototype? Vessel { get; private set; }

    public ShipyardPreviewWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        GuidebookButton.OnPressed += _ => OpenGuidebook();
    }

    /// <summary>
    /// Shows the vessel. Returns false when there is no pre-rendered image and the tile layout must be requested.
    /// </summary>
    public bool SetVessel(VesselPrototype vessel)
    {
        Vessel = vessel;
        NameLabel.Text = vessel.Name;
        DescriptionLabel.SetMessage(FormattedMessage.FromUnformatted(vessel.Description));
        GuidebookButton.Disabled = vessel.GuidebookPage == null;

        Preview.Clear();

        var path = RenderPath(vessel.ShuttlePath);
        if (_resourceCache.ContentFileExists(path)
            && _resourceCache.TryGetResource<TextureResource>(path, out var texture))
        {
            RenderRect.Texture = texture.Texture;
            RenderRect.Visible = true;
            Preview.Visible = false;
            LoadingLabel.Visible = false;
            return true;
        }

        RenderRect.Texture = null;
        RenderRect.Visible = false;
        Preview.Visible = true;
        LoadingLabel.Visible = true;
        return false;
    }

    /// <summary>
    /// /Maps/_NF/Shuttles/adder.yml -> /Textures/_Horizon/Shipyard/Previews/_NF_Shuttles_adder.png
    /// Must match preview_key in Tools/_Horizon/render_shipyard_previews.py.
    /// </summary>
    private static ResPath RenderPath(ResPath shuttlePath)
    {
        var key = shuttlePath.ToString();
        if (key.StartsWith("/Maps/"))
            key = key["/Maps/".Length..];
        if (key.EndsWith(".yml"))
            key = key[..^".yml".Length];

        return RenderDirectory / (key.Replace('/', '_') + ".png");
    }

    public void SetPreview(Vector2i[] tiles, Color[] colors)
    {
        Preview.SetPreview(tiles, colors);
        LoadingLabel.Visible = !Preview.HasPreview;
    }

    private void OpenGuidebook()
    {
        if (Vessel?.GuidebookPage is not { } page)
            return;

        _entitySystem.GetEntitySystem<GuidebookSystem>()
            .OpenHelp(new List<ProtoId<GuideEntryPrototype>> { page });
    }
}
