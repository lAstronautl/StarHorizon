using Content.Client.UserInterface.Controls;
using Content.Shared._Horizon._Fractions.AnCo.WeaponCaseHack;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Horizon._Fractions.AnCo.WeaponCaseHack;

[GenerateTypedNameReferences]
public sealed partial class AnCoWeaponCaseHackWindow : FancyWindow
{
    public event Action<AnCoHackDir, int>? OnChoose;

    [Dependency] private readonly IGameTiming _timing = default!;

    private static readonly Color TimerNormal = Color.White;
    private static readonly Color TimerWarning = Color.FromHex("#ff4040");
    private const double WarningSeconds = 10;

    private int _nodeIndex;
    private TimeSpan? _deadline;

    public AnCoWeaponCaseHackWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        LeftButton.OnPressed += _ => OnChoose?.Invoke(AnCoHackDir.Left, _nodeIndex);
        UpButton.OnPressed += _ => OnChoose?.Invoke(AnCoHackDir.Up, _nodeIndex);
        RightButton.OnPressed += _ => OnChoose?.Invoke(AnCoHackDir.Right, _nodeIndex);
    }

    public void UpdateState(AnCoHackBoundUserInterfaceState state)
    {
        _nodeIndex = state.NodeIndex;
        _deadline = state.Deadline;
        UpdateTimer();

        AttemptsLabel.Text = Loc.GetString("anco-weapon-case-hack-attempts",
            ("attempts", state.Attempts), ("max", state.MaxAttempts));
        RuleLabel.SetMarkup(Loc.GetString(state.RuleLocId));

        // Серийник подписан направлением, в котором лежит его дорожка.
        SerialLeftLabel.Text = $"{Arrow(state.CurrentLeftExit)} {state.SerialB}";
        SerialRightLabel.Text = $"{Arrow(state.CurrentRightExit)} {state.SerialC}";

        // Кнопка направления без выхода неактивна.
        LeftButton.Disabled = !HasExit(state, AnCoHackDir.Left);
        UpButton.Disabled = !HasExit(state, AnCoHackDir.Up);
        RightButton.Disabled = !HasExit(state, AnCoHackDir.Right);

        Map.Update(state);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateTimer();
    }

    private void UpdateTimer()
    {
        if (_deadline is not { } deadline)
        {
            // Таймер стартует с первого ответа.
            TimerLabel.Text = Loc.GetString("anco-weapon-case-hack-timer-idle");
            TimerLabel.FontColorOverride = TimerNormal;
            return;
        }

        var left = Math.Max(0, (deadline - _timing.CurTime).TotalSeconds);
        TimerLabel.Text = Loc.GetString("anco-weapon-case-hack-timer", ("seconds", (int) Math.Ceiling(left)));
        TimerLabel.FontColorOverride = left <= WarningSeconds ? TimerWarning : TimerNormal;
    }

    private static bool HasExit(AnCoHackBoundUserInterfaceState state, AnCoHackDir dir)
    {
        return state.CurrentLeftExit == dir || state.CurrentRightExit == dir;
    }

    private static string Arrow(AnCoHackDir dir)
    {
        return dir switch
        {
            AnCoHackDir.Left => Loc.GetString("anco-weapon-case-hack-dir-left"),
            AnCoHackDir.Up => Loc.GetString("anco-weapon-case-hack-dir-up"),
            _ => Loc.GetString("anco-weapon-case-hack-dir-right"),
        };
    }
}
