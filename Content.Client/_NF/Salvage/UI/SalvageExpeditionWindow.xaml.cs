using System.Globalization;
using Content.Client.UserInterface.Controls;
using Content.Shared.Procedural;
using Content.Shared.Salvage.Expeditions;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._NF.Salvage.UI;

/// <summary>
/// Консоль экспедиций: на каких планетах какая экспедиция и сколько времени осталось. Экспедицию запускает дроп-под.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SalvageExpeditionWindow : FancyWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;
    [Dependency] private readonly IPrototypeManager _proto = default!;

    private static readonly Color PanelColor = new(30, 30, 34);
    private static readonly Color Gold = Color.FromHex("#A88B5E");
    private static readonly Color Muted = Color.FromHex("#9AA0AA");
    private static readonly Color Good = Color.FromHex("#5FD35F");

    private readonly List<(Label Status, PlanetExpeditionInfo Info)> _statuses = new();

    public SalvageExpeditionWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        HintLabel.Text = Loc.GetString("salvage-expedition-window-hint");
        HintLabel.FontColorOverride = Muted;
    }

    /// <summary>Перестраивает список: по строке на планету.</summary>
    public void SetPlanets(List<PlanetExpeditionInfo> planets)
    {
        Rows.DisposeAllChildren();
        _statuses.Clear();

        foreach (var info in planets)
        {
            var type = Loc.GetString($"salvage-expedition-type-{info.Mission.MissionType}");
            var difficulty = Loc.GetString($"salvage-expedition-difficulty-{info.Mission.Difficulty}");
            var difficultyColor = _proto.TryIndex<SalvageDifficultyPrototype>(info.Mission.Difficulty, out var proto)
                ? proto.Color
                : Color.White;

            var name = new Label
            {
                Text = info.Name,
                FontColorOverride = Gold,
                MinWidth = 200,
            };

            var mission = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
            mission.AddChild(new Label { Text = type });
            mission.AddChild(new Label { Text = difficulty, FontColorOverride = difficultyColor });

            var status = new Label { MinWidth = 220, HorizontalAlignment = Control.HAlignment.Right };

            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 12, Margin = new Thickness(8, 6) };
            row.AddChild(name);
            row.AddChild(mission);
            row.AddChild(status);

            Rows.AddChild(new PanelContainer
            {
                PanelOverride = new StyleBoxFlat(PanelColor),
                HorizontalExpand = true,
                Children = { row },
            });

            _statuses.Add((status, info));
        }

        UpdateStatuses();
    }

    private void UpdateStatuses()
    {
        foreach (var (label, info) in _statuses)
        {
            switch (info.Status)
            {
                case PlanetExpeditionStatus.Idle:
                    var idleLeft = info.EndTime - _timing.CurTime;
                    if (idleLeft < TimeSpan.Zero)
                        idleLeft = TimeSpan.Zero;
                    label.Text = Loc.GetString("salvage-expedition-planet-status-idle",
                        ("time", $"{(int) idleLeft.TotalMinutes:00}:{idleLeft.Seconds:00}"));
                    label.FontColorOverride = Muted;
                    break;
                case PlanetExpeditionStatus.Generating:
                    label.Text = Loc.GetString("salvage-expedition-planet-status-generating");
                    label.FontColorOverride = Gold;
                    break;
                default:
                    var remaining = info.EndTime - _timing.CurTime;
                    label.Text = remaining <= TimeSpan.Zero
                        ? Loc.GetString("salvage-expedition-planet-status-closing")
                        : Loc.GetString("salvage-expedition-planet-status-active",
                            ("time", $"{(int) remaining.TotalMinutes:00}:{remaining.Seconds:00}"));
                    label.FontColorOverride = Good;
                    break;
            }
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateStatuses();
    }
}
