using Content.Shared._NF.Shipyard.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NF.Shipyard.UI;

[GenerateTypedNameReferences]
public sealed partial class VesselRow : PanelContainer
{
    public VesselPrototype? Vessel;

    /// <summary>
    /// Horizon: raised when the preview button is pressed (replaces the old guidebook button).
    /// </summary>
    public event Action<VesselPrototype>? OnPreviewPressed;

    public VesselRow()
    {
        RobustXamlLoader.Load(this);

        Preview.OnPressed += _ =>
        {
            if (Vessel != null)
                OnPreviewPressed?.Invoke(Vessel);
        };
    }
}
